// Battle textures: battler-<hero> for heroes, and the plain enemy keys for enemies
export const createBattlers = (scene) => {
  Object.entries(HEROES).forEach(([name, hero]) =>
    createTexture(scene, `battler-${name}`, hero.rows, hero.palette)
  )
  Object.entries(ENEMIES).forEach(([key, enemy]) =>
    createTexture(scene, key, mirror(enemy.art), enemy.palette)
  )
}
